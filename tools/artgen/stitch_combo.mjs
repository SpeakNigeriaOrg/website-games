// Stitches the sentence each Who-does-what combination says, "<animal> ń <action>" ("ajá ń sùn", the dog is
// sleeping), for Puppet Theatre and Windows: the kit's own recordings of the two words with Femi's recorded ń
// between them, the version the owner chose by ear (2026-11-21: the isolated ń, not one cut from a phrase).
//   node tools/artgen/stitch_combo.mjs        (after every kit rebuild: the kit's audio files change)
// Writes dev/games/art/combo/<name>_say.mp3 and dev/games/combo_say.js (what combo.js reads: the file, and when the
// action word starts, so a game can light the action's picture as it is said).
//
// Each word is the kit's voice for it (Femi where he has a usable take; sáré is Tolani's, a change of speaker the
// owner accepted), cut to its aligned span (naturalSyllables) with 40 ms before and 80 ms after; a word without an
// alignment (the legacy adìyẹ and màlúù, Tolani's sáré) is its whole processed clip, whose ends the conditioning
// already trimmed. ń is Femi's n_is, cut to 0.50-0.84 s: its measured sound (0.52-0.82 s; the alignment's 0.42-1.04
// s is loose, and the recording starts with a record-button thump) - so a new recording of ń must be measured again,
// and this refuses to run on any other file. Pieces are joined with 60 ms of silence, with 10/15 ms fades.
import { spawnSync } from 'node:child_process';
import fs from 'node:fs';
import { SUBJECTS, ACTIONS } from '../../dev/games/combo.js';

const games = new URL('../../dev/games/', import.meta.url);
const kitDir = new URL('content/', games);
const outDir = new URL('art/combo/', games);
const SR = 48000, PRE = 0.04, POST = 0.08, GAP = 0.06;
const N_AUDIO = 'audio/e0713444-9285-436f-ac0d-fcbbe581be02.mp3', N_SPAN = [0.50, 0.84];

const kit = JSON.parse(fs.readFileSync(new URL('content.json', kitDir), 'utf8'));
const words = new Map(kit.words.map((w) => [w.id, w]));
const pcm = (rel) => {
  const r = spawnSync('ffmpeg', ['-v', 'error', '-i', new URL(rel, kitDir).pathname.replace(/^\/(\w:)/, '$1'), '-ac', '1', '-ar', String(SR), '-f', 'f32le', '-'], { maxBuffer: 1 << 28 });
  if (r.status !== 0) throw new Error(`cannot decode ${rel}: ${r.stderr}`);
  return new Float32Array(r.stdout.buffer, r.stdout.byteOffset, r.stdout.length / 4);
};

function piece(w, span, margins) {
  const x = pcm(w.audio), dur = x.length / SR;
  const s = w.naturalSyllables;
  const [from, to] = span ?? (s?.length ? [s[0].startS - margins[0], s[s.length - 1].endS + margins[1]] : [0, dur]);
  const y = x.slice(Math.floor(Math.max(0, from) * SR), Math.floor(Math.min(dur, to) * SR));
  const fi = Math.floor(0.01 * SR), fo = Math.floor(0.015 * SR);
  for (let i = 0; i < fi && i < y.length; i++) y[i] *= i / fi;
  for (let i = 0; i < fo && i < y.length; i++) y[y.length - 1 - i] *= i / fo;
  return y;
}

const n = words.get('n_is');
if (n?.audio !== N_AUDIO) throw new Error(`ń is now ${n?.audio}, not the recording measured (${N_AUDIO}): measure its sound span again`);
const nPiece = piece(n, N_SPAN);
const gap = new Float32Array(Math.floor(GAP * SR));
const say = {};
for (const sub of SUBJECTS) for (const act of ACTIONS) {
  const s = words.get(sub.id), a = words.get(act.id), name = `${sub.key}_${act.key}`;
  if (!s?.audio || !a?.audio) { console.log(`${name}: skipped (no ${!s?.audio ? sub.id : act.id} in the kit)`); continue; }
  const parts = [piece(s, null, [PRE, POST]), gap, nPiece, gap, piece(a, null, [PRE, POST])];
  const y = new Float32Array(parts.reduce((t, p) => t + p.length, 0));
  let o = 0; for (const p of parts) { y.set(p, o); o += p.length; }
  const actionAt = (y.length - parts[4].length) / SR;
  const raw = new URL(`${name}_say.f32`, outDir).pathname.replace(/^\/(\w:)/, '$1');
  fs.writeFileSync(raw, Buffer.from(y.buffer, y.byteOffset, y.byteLength));
  const r = spawnSync('ffmpeg', ['-v', 'error', '-y', '-f', 'f32le', '-ar', String(SR), '-ac', '1', '-i', raw, '-c:a', 'libmp3lame', '-q:a', '2',
    raw.replace(/\.f32$/, '.mp3')]);
  fs.rmSync(raw);
  if (r.status !== 0) throw new Error(`${name}: encode failed: ${r.stderr}`);
  say[name] = { audio: `combo/${name}_say.mp3`, actionAt: +actionAt.toFixed(3), voices: [s.voice, n.voice, a.voice] };
  console.log(`${name}: ${(y.length / SR).toFixed(2)} s, action at ${actionAt.toFixed(2)} s (${say[name].voices.join(' / ')})`);
}
fs.writeFileSync(new URL('combo_say.js', games), `// Generated by tools/artgen/stitch_combo.mjs - do not edit. The sentence each combination says ("ajá ń sùn"),
// stitched from the kit's recordings; actionAt is when the action word starts (s).
export const SAY = ${JSON.stringify(say, null, 2)};
`);
console.log(`${Object.keys(say).length} sentences -> dev/games/combo_say.js`);
